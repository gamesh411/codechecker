class TestConstraintTrace(unittest.TestCase):

    def setup_class(self):
        global TEST_WORKSPACE
        TEST_WORKSPACE = env.get_workspace('constraint_trace')
        os.environ['TEST_WORKSPACE'] = TEST_WORKSPACE

        test_env = env.test_env(TEST_WORKSPACE)

        codechecker_cfg = {
            'check_env': test_env,
            'workspace': TEST_WORKSPACE,
            'run_names': [],
            'analyzers': ['clangsa']
        }

        # pytest does not run teardown_class after a failed setup_class, and
        # runs setup_class again for the next test. The product would be
        # left behind on the global server, and every later test would fail
        # with "Failed to add the product" instead of the first real error.
        try:
            server_access = codechecker.start_or_get_server()
            server_access['viewer_product'] = 'constraint_trace'
            codechecker_cfg.update(server_access)
            # Before the product exists, so that a failed setup can remove it.
            env.export_test_cfg(TEST_WORKSPACE,
                                {'codechecker_cfg': codechecker_cfg})
            codechecker.add_test_package_product(server_access, TEST_WORKSPACE)

            # several_contexts last: trimmed_paths stores it again.
            for run_name in ['with_snapshots', 'no_snapshots', 'no_smtlib',
                             'v1_trace', 'z3_refuted',
                             'concrete_value', 'opaque_call',
                             'call_result', 'no_symbols',
                             'replaced_field', 'widened_loop',
                             'access_path', 'caller_frames',
                             'several_contexts']:
                report_dir = os.path.join(
                    TEST_WORKSPACE, 'test_proj', run_name)
                shutil.copytree(
                    os.path.join(project.path('constraint_trace'), run_name),
                    report_dir)

                for plist in glob.glob(os.path.join(report_dir, '*.plist')):
                    with open(plist, 'r+', encoding="utf-8") as plist_file:
                        content = plist_file.read()
                        plist_file.seek(0)
                        plist_file.truncate()
                        plist_file.write(
                            content.replace("$FILE_PATH$", report_dir))

                codechecker_cfg['reportdir'] = report_dir
                if codechecker.store(codechecker_cfg, run_name):
                    raise RuntimeError(f"Failed to store '{run_name}'")
                codechecker_cfg['run_names'].append(run_name)

            # The same reports again, with the workspace cut off their paths.
            codechecker_cfg['reportdir'] = report_dir
            codechecker_cfg['trim_path_prefix'] = TEST_WORKSPACE
            if codechecker.store(codechecker_cfg, 'trimmed_paths'):
                raise RuntimeError("Failed to store 'trimmed_paths'")
            del codechecker_cfg['trim_path_prefix']
            codechecker_cfg['run_names'].append('trimmed_paths')

            env.export_test_cfg(TEST_WORKSPACE,
                                {'codechecker_cfg': codechecker_cfg})
        except BaseException:
            TestConstraintTrace.teardown_class(self)
            raise

    def teardown_class(self):
        global TEST_WORKSPACE
        check_env = env.import_test_cfg(TEST_WORKSPACE)[
            'codechecker_cfg']['check_env']
        codechecker.remove_test_package_product(TEST_WORKSPACE, check_env)
        shutil.rmtree(TEST_WORKSPACE, ignore_errors=True)

    def setup_method(self, _):
        self._test_workspace = os.environ.get('TEST_WORKSPACE')
        self._cc_client = env.setup_viewer_client(self._test_workspace)
        self.assertIsNotNone(self._cc_client)

    def _report_id(self, run_name):
        run_filter = RunFilter(names=[run_name], exactMatch=True)
        run_id = self._cc_client.getRunData(
            run_filter, MAX_QUERY_SIZE, 0, None)[0].runId

        reports = self._cc_client.getRunResults(
            [run_id], MAX_QUERY_SIZE, 0, [], ReportFilter(), None, False)
        self.assertEqual(len(reports), 1)

        return reports[0].reportId

    def _details(self, run_name):
        return self._cc_client.getReportDetails(self._report_id(run_name))

    @staticmethod
    def _trace_of(details):
        """ The stored trace with each step's whole snapshot in the step. """
        raw = json.loads(details.constraintTrace)
        trace = ConstraintTrace(raw)
        return {**raw, 'cfgs': trace.cfgs(),
                'steps': [{**step, **trace.snapshot(step['exploded_node'])}
                          for step in raw['steps']]}

    def _trace(self, run_name):
        return self._trace_of(self._details(run_name))

    def _event_step(self, run_name, message):
        """ The `order` of the event Path Step with the given message. """
        details = self._details(run_name)
        index = [event.msg for event in details.pathEvents].index(message)
        return next(step['order']
                    for step in json.loads(details.constraintTrace)['steps']
                    if step['kind'] == 'event' and step['index'] == index)

    def _check(self, run_name, *constraints, with_example=False):
        return self._cc_client.checkWhatIf(
            self._report_id(run_name),
            [WhatIfConstraint(*constraint) for constraint in constraints],
            with_example)

    def _example(self, run_name, *constraints):
        """ The example of the path as {symbol: value}, or None. """
        result = self._check(run_name, *constraints, with_example=True)
        return result, None if result.example is None else \
            {value.symbol: value.value for value in result.example}

    def _first_step_constraining(self, run_name, symbol_prefix):
        """ The `order` of the first step whose path condition has it. """
        trace = self._trace(run_name)
        return min(step['order'] for step in trace['steps']
                   if any(entry['symbol'].startswith(symbol_prefix)
                          for entry in step['path_condition']))

    def test_every_event_carries_symbol_ranges(self):
        """
        The stored snapshot of each event Path Step comes back keyed to its
        position among the report's path events.
        """
        details = self._details('with_snapshots')

        raw = json.loads(details.constraintTrace)
        self.assertEqual(raw['version'], 2)
        trace = self._trace_of(details)
        event_steps = [step for step in trace['steps']
                       if step['kind'] == 'event']
        self.assertEqual(
            [step['index'] for step in event_steps],
            list(range(len(details.pathEvents))))

        # Hand-derived from demo/two-path.c: Bug Path a == 0, b != 0.
        self.assertEqual(
            details.pathEvents[0].msg, "Assuming 'a' is equal to 0")
        self.assertEqual(event_steps[0]['symbol_ranges'], [
            {'symbol': 'reg_$1<int a>', 'range': '{ [0, 0] }'}])

        self.assertEqual(
            details.pathEvents[1].msg, "Assuming 'b' is not equal to 0")
        self.assertEqual(event_steps[1]['symbol_ranges'], [
            {'symbol': 'reg_$1<int a>', 'range': '{ [0, 0] }'},
            {'symbol': 'reg_$2<int b>',
             'range': '{ [-2147483648, -1], [1, 2147483647] }'}])

    def test_snapshot_maps_variables_to_values(self):
        """
        Each step names its visible variables, resolved to the symbols the
        ranges are keyed by or to a concrete value.
        """
        details = self._details('with_snapshots')

        trace = self._trace_of(details)
        first_event = next(step for step in trace['steps']
                           if step['kind'] == 'event')
        variables = {variable['name']: variable
                     for variable in first_event['variables']}

        # Hand-derived from demo/two-path.c: f's parameters and local. A
        # symbol also has its SMT-LIB term, named like the symbol's dump.
        self.assertEqual(variables['a'], {
            'name': 'a', 'value': 'reg_$1<int a>', 'kind': 'symbol',
            'smt': 'reg_$1', 'smt_signed': True})
        self.assertEqual(variables['b'], {
            'name': 'b', 'value': 'reg_$2<int b>', 'kind': 'symbol',
            'smt': 'reg_$2', 'smt_signed': True})
        self.assertEqual(variables['p'], {
            'name': 'p', 'value': '0', 'kind': 'integer'})

