    def test_control_flow_graph_survives_store(self):
        """
        The trace carries the function's CFG once, and each Path Step says
        where in it it is, so the UI can map graph elements back to steps.
        """
        details = self._details('with_snapshots')

        trace = self._trace_of(details)
        self.assertEqual([cfg['function'] for cfg in trace['cfgs']], ['f'])
        cfg = trace['cfgs'][0]
        blocks = {block['id']: block for block in cfg['blocks']}
        self.assertEqual(cfg['blocks'][0]['id'], cfg['entry'])
        self.assertIn(cfg['entry'], cfg['path_blocks'])
        self.assertTrue(all(
            edge['from'] in cfg['path_blocks'] and
            edge['to'] in cfg['path_blocks'] for edge in cfg['path_edges']))
        self.assertTrue(all(step['cfg_position']['cfg'] == 0 and
                            step['cfg_position']['block'] in blocks
                            for step in trace['steps']))

        def element_of(message):
            index = [event.msg for event in details.pathEvents].index(message)
            position = next(
                step['cfg_position'] for step in trace['steps']
                if step['kind'] == 'event' and step['index'] == index)
            block = blocks[position['block']]
            return block, block['elements'][position['element']]

        # Hand-derived from demo/two-path.c: a == 0 is first assumed on line 7,
        # where `if (a != 0)` takes its false branch and skips `p = &x`. The
        # store the dereference's null comes from is the one on line 14.
        block, element = element_of("Assuming 'a' is equal to 0")
        self.assertEqual(
            (element['text'], element['line']), ('a != 0', 7))
        self.assertEqual(block['terminator'], 'if a != 0')
        then_block, else_block = block['successors']
        self.assertNotIn(then_block, cfg['path_blocks'])
        self.assertIn({'from': block['id'], 'to': else_block},
                      cfg['path_edges'])
        _, element = element_of("Null pointer value stored to 'p'")
        self.assertEqual((element['text'], element['line']), ('p = 0', 14))
        self.assertNotIn('parent', element)

    def test_exploded_nodes_tell_calling_contexts_apart(self):
        """
        Each Path Step names the analyzer node it came from, with that node's
        stack of call sites and location, so one statement reached through
        two calls reads as two states. Locations name their file by path,
        since the plist's file indices do not survive storage.
        """
        details = self._details('several_contexts')
        trace = json.loads(details.constraintTrace)
        nodes = trace['exploded_nodes']
        frames = trace['stack_frames']

        self.assertEqual(
            [node['path_position'] for node in nodes],
            sorted(node['path_position'] for node in nodes))
        self.assertTrue(all(0 <= step['exploded_node'] < len(nodes)
                            for step in trace['steps']))

        def node_of(message, occurrence):
            indices = [i for i, event in enumerate(details.pathEvents)
                       if event.msg == message]
            step = next(step for step in trace['steps']
                        if step['kind'] == 'event' and
                        step['index'] == indices[occurrence])
            return nodes[step['exploded_node']]

        def stack_of(node):
            stack = []
            index = node['frame']
            while index is not None:
                frame = frames[index]
                call_site = frame.get('call_site')
                stack.append((frame['function'],
                              call_site and call_site['line']))
                index = frame.get('parent')
            return stack

        # Hand-derived from demo/several-contexts.c: `take` is called on
        # lines 13 and 14, and both calls assume on `if (flag)`, line 5.
        first = node_of("Assuming 'flag' is not equal to 0", 0)
        second = node_of("Assuming 'flag' is 0", 0)
        self.assertEqual(first['location']['line'], 5)
        self.assertEqual(second['location']['line'], 5)
        self.assertTrue(first['location']['file'].endswith(
            os.path.join('several_contexts', 'several_contexts.c')))
        self.assertEqual(stack_of(first),
                         [('take', 13), ('several_contexts', None)])
        self.assertEqual(stack_of(second),
                         [('take', 14), ('several_contexts', None)])
        self.assertTrue(frames[first['frame']]['call_site']['file'].endswith(
            'several_contexts.c'))

        # A call's two events share the call's node, in the caller.
        self.assertEqual(node_of("Calling 'take'", 1),
                         node_of("Entered call from 'several_contexts'", 1))
        self.assertEqual(node_of("Calling 'take'", 1)['kind'], 'CallEnter')

    def test_trim_path_prefix_applies_to_trace_locations(self):
        """
        `--trim-path-prefix` cuts the paths of the trace's locations like
        every other path of a stored report.
        """
        details = self._details('trimmed_paths')
        trace = json.loads(details.constraintTrace)
        trimmed = os.path.join('test_proj', 'several_contexts',
                               'several_contexts.c')

        self.assertTrue(trace['exploded_nodes'])
        self.assertTrue(all(node['location']['file'] == trimmed
                            for node in trace['exploded_nodes']))
        call_sites = [frame['call_site']['file']
                      for frame in trace['stack_frames']
                      if 'call_site' in frame]
        self.assertTrue(call_sites)
        self.assertEqual(set(call_sites), {trimmed})
        self.assertTrue(all(event.filePath == trimmed
                            for event in details.pathEvents))

    def test_trace_is_stored_one_snapshot_per_node(self):
        """
        The stored trace keeps the version 2 encoding: each node's snapshot
        as the change from the node before it and each string once, so its
        size grows with the Bug Path, and nothing expands it on the way.
        """
        raw = json.loads(self._details('with_snapshots').constraintTrace)

        self.assertEqual(len(raw['strings']), len(set(raw['strings'])))
        self.assertTrue(all(set(step) == {'kind', 'index', 'order',
                                          'exploded_node'}
                            for step in raw['steps']))
        # Hand-derived from demo/two-path.c: a == 0 and then b != 0 are
        # assumed, so the path condition gains one entry at a time.
        added = [len(node['path_condition'].get('insert', []))
                 for node in raw['exploded_nodes']
                 if 'path_condition' in node]
        self.assertEqual(added, [1, 1])
        self.assertFalse(any('remove' in node.get('path_condition', {})
                             for node in raw['exploded_nodes']))

    def test_stored_trace_keeps_its_symbol_table(self):
        """
        Hand-derived from demo/call-result.c: the length is the result of
        `read_len()`, called in `next_len`, a callee the Bug Path leaves out,
        so its frame is not in the trace; `malloc` is modelled by a checker,
        so the analyzer recorded no reason for its value. Origins name their
        file by its stored path, as the trace's other locations do.
        """
        details = self._details('call_result')
        trace = ConstraintTrace(json.loads(details.constraintTrace))
        symbols = trace.symbols()
        source = os.path.join(self._test_workspace, 'test_proj',
                              'call_result', 'call_result.c')

        by_callee = {symbol['origin'].get('callee'): (dump, symbol)
                     for dump, symbol in symbols.items()
                     if 'origin' in symbol}
        self.assertEqual(set(by_callee), {'read_len', 'malloc'})
        dump, read_len = by_callee['read_len']
        self.assertTrue(dump.startswith('conj_$'))
        self.assertEqual(read_len['kind'], 'conjured')
        self.assertEqual(read_len['origin'], {
            'reason': 'call_result', 'statement': 'read_len()',
            'callee': 'read_len', 'function': 'next_len',
            'location': {'line': 8, 'col': 36, 'file': source}})
        self.assertIn('smt', read_len)
        malloc = by_callee['malloc'][1]['origin']
        self.assertEqual((malloc['reason'], malloc['function'],
                          malloc['statement'], malloc['location']['line']),
                         ('other', 'copy', 'malloc(16)', 11))
        self.assertEqual(
            trace.trace['stack_frames'][malloc['frame']]['function'], 'copy')
        # The parameter `out` has an entry with no origin.
        self.assertIn({'kind': 'region_value'},
                      [{'kind': symbol['kind']}
                       for symbol in symbols.values()
                       if 'origin' not in symbol])

        # Every symbol the last path condition names has an entry.
        last = trace.snapshot(len(trace.nodes) - 1)
        self.assertTrue(last['path_condition'])
        self.assertTrue(all(entry['symbol'] in symbols
                            for entry in last['path_condition']))

    def test_stored_trace_keeps_the_type_of_symbols(self):
        """
        Hand-derived from demo/call-result.c and demo/replaced-field.c: the
        length `read_len()` returns is an `int`, the `malloc` a checker
        models is a `void *` the analyzer treats as an address, and `Tok.Kind`
        derives from a value that replaced `Tok`, so its dump says nothing of
        its type but its entry does.
        """
        symbols = self._symbols('call_result')[0]
        by_callee = {symbol['origin'].get('callee'): symbol
                     for symbol in symbols.values() if 'origin' in symbol}
        self.assertEqual(by_callee['read_len']['type'], 'int')
        self.assertNotIn('pointer', by_callee['read_len'])
        self.assertEqual(by_callee['malloc']['type'], 'void *')
        self.assertTrue(by_callee['malloc']['pointer'])

        symbols = self._symbols('replaced_field')[0]
        field = next(symbol for symbol in symbols.values()
                     if symbol['kind'] == 'derived')
        self.assertEqual(field['type'], 'int')
        self.assertNotIn('pointer', field)
        self.assertTrue(any(symbol.get('pointer')
                            for symbol in symbols.values()))

