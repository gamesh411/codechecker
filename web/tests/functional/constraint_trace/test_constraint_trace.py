"""
Test that Constraint Snapshots stored from a Clang plist reach the report
details API. The fixtures are generated by `dev-loop.sh fixture` from the
Colorful Day Clang; they are the contract between the two repositories.
"""


import glob
import json
import os
import shutil
import sqlite3
import sys
import unittest

from libtest import codechecker
from libtest import env
from libtest import project

from codechecker_api.python.DBAccess_v6.ttypes import PathVerdict, \
    ReportFilter, RunFilter, WhatIfConstraint
from codechecker_api.python.DBAccess_v6.constants import MAX_QUERY_SIZE


class TestConstraintTrace(unittest.TestCase):

    def setup_class(self):
        global TEST_WORKSPACE
        TEST_WORKSPACE = env.get_workspace('constraint_trace')
        os.environ['TEST_WORKSPACE'] = TEST_WORKSPACE

        test_env = env.test_env(TEST_WORKSPACE)

        codechecker_cfg = {
            'check_env': test_env,
            'workspace': TEST_WORKSPACE,
            'run_names': [],
            'analyzers': ['clangsa']
        }

        server_access = codechecker.start_or_get_server()
        server_access['viewer_product'] = 'constraint_trace'
        codechecker.add_test_package_product(server_access, TEST_WORKSPACE)
        codechecker_cfg.update(server_access)

        for run_name in ['with_snapshots', 'no_snapshots', 'no_smtlib',
                         'z3_refuted', 'concrete_value', 'opaque_call']:
            report_dir = os.path.join(TEST_WORKSPACE, 'test_proj', run_name)
            shutil.copytree(
                os.path.join(project.path('constraint_trace'), run_name),
                report_dir)

            for plist in glob.glob(os.path.join(report_dir, '*.plist')):
                with open(plist, 'r+', encoding="utf-8") as plist_file:
                    content = plist_file.read()
                    plist_file.seek(0)
                    plist_file.truncate()
                    plist_file.write(
                        content.replace("$FILE_PATH$", report_dir))

            codechecker_cfg['reportdir'] = report_dir
            if codechecker.store(codechecker_cfg, run_name):
                sys.exit(1)
            codechecker_cfg['run_names'].append(run_name)

        env.export_test_cfg(TEST_WORKSPACE,
                            {'codechecker_cfg': codechecker_cfg})

    def teardown_class(self):
        global TEST_WORKSPACE
        check_env = env.import_test_cfg(TEST_WORKSPACE)[
            'codechecker_cfg']['check_env']
        codechecker.remove_test_package_product(TEST_WORKSPACE, check_env)
        shutil.rmtree(TEST_WORKSPACE, ignore_errors=True)

    def setup_method(self, _):
        self._test_workspace = os.environ.get('TEST_WORKSPACE')
        self._cc_client = env.setup_viewer_client(self._test_workspace)
        self.assertIsNotNone(self._cc_client)

    def _report_id(self, run_name):
        run_filter = RunFilter(names=[run_name], exactMatch=True)
        run_id = self._cc_client.getRunData(
            run_filter, MAX_QUERY_SIZE, 0, None)[0].runId

        reports = self._cc_client.getRunResults(
            [run_id], MAX_QUERY_SIZE, 0, [], ReportFilter(), None, False)
        self.assertEqual(len(reports), 1)

        return reports[0].reportId

    def _details(self, run_name):
        return self._cc_client.getReportDetails(self._report_id(run_name))

    def _event_step(self, run_name, message):
        """ The `order` of the event Path Step with the given message. """
        details = self._details(run_name)
        index = [event.msg for event in details.pathEvents].index(message)
        return next(step['order']
                    for step in json.loads(details.constraintTrace)['steps']
                    if step['kind'] == 'event' and step['index'] == index)

    def _check(self, run_name, *constraints):
        return self._cc_client.checkWhatIf(
            self._report_id(run_name),
            [WhatIfConstraint(*constraint) for constraint in constraints])

    def _first_step_constraining(self, run_name, symbol_prefix):
        """ The `order` of the first step whose path condition has it. """
        trace = json.loads(self._details(run_name).constraintTrace)
        return min(step['order'] for step in trace['steps']
                   if any(entry['symbol'].startswith(symbol_prefix)
                          for entry in step['path_condition']))

    def test_every_event_carries_symbol_ranges(self):
        """
        The stored snapshot of each event Path Step comes back keyed to its
        position among the report's path events.
        """
        details = self._details('with_snapshots')

        trace = json.loads(details.constraintTrace)
        self.assertEqual(trace['version'], 1)
        event_steps = [step for step in trace['steps']
                       if step['kind'] == 'event']
        self.assertEqual(
            [step['index'] for step in event_steps],
            list(range(len(details.pathEvents))))

        # Hand-derived from demo/two-path.c: Bug Path a == 0, b != 0.
        self.assertEqual(
            details.pathEvents[0].msg, "Assuming 'a' is equal to 0")
        self.assertEqual(event_steps[0]['symbol_ranges'], [
            {'symbol': 'reg_$1<int a>', 'range': '{ [0, 0] }'}])

        self.assertEqual(
            details.pathEvents[1].msg, "Assuming 'b' is not equal to 0")
        self.assertEqual(event_steps[1]['symbol_ranges'], [
            {'symbol': 'reg_$1<int a>', 'range': '{ [0, 0] }'},
            {'symbol': 'reg_$2<int b>',
             'range': '{ [-2147483648, -1], [1, 2147483647] }'}])

    def test_snapshot_maps_variables_to_values(self):
        """
        Each step names its visible variables, resolved to the symbols the
        ranges are keyed by or to a concrete value.
        """
        details = self._details('with_snapshots')

        trace = json.loads(details.constraintTrace)
        first_event = next(step for step in trace['steps']
                           if step['kind'] == 'event')
        variables = {variable['name']: variable
                     for variable in first_event['variables']}

        # Hand-derived from demo/two-path.c: f's parameters and local. A
        # symbol also has its SMT-LIB term, named like the symbol's dump.
        self.assertEqual(variables['a'], {
            'name': 'a', 'value': 'reg_$1<int a>', 'kind': 'symbol',
            'smt': 'reg_$1', 'smt_signed': True})
        self.assertEqual(variables['b'], {
            'name': 'b', 'value': 'reg_$2<int b>', 'kind': 'symbol',
            'smt': 'reg_$2', 'smt_signed': True})
        self.assertEqual(variables['p'], {
            'name': 'p', 'value': '0', 'kind': 'integer'})

    def test_path_condition_keeps_dead_symbols(self):
        """
        Symbols dropped as dead vanish from the known ranges of later steps
        but stay in the accumulated path condition.
        """
        details = self._details('with_snapshots')

        trace = json.loads(details.constraintTrace)
        last_step = [step for step in trace['steps']
                     if step['kind'] == 'event'][-1]

        self.assertEqual(last_step['symbol_ranges'], [])
        self.assertEqual(last_step['path_condition'], [
            {'symbol': 'reg_$1<int a>', 'range': '{ [0, 0] }'},
            {'symbol': 'reg_$2<int b>',
             'range': '{ [-2147483648, -1], [1, 2147483647] }'}])

    def test_control_steps_survive_store(self):
        """
        A control-flow Path Step comes back keyed to the position its edge
        ends at, carrying the snapshot taken there.
        """
        details = self._details('with_snapshots')

        trace = json.loads(details.constraintTrace)
        control_steps = [step for step in trace['steps']
                         if step['kind'] == 'control']
        self.assertTrue(control_steps)
        self.assertTrue(all(
            0 <= step['index'] < len(details.executionPath)
            for step in control_steps))

        # Hand-derived from demo/two-path.c: the edge into `p = 0` on line 14.
        # b's range is held by the path condition, because b is dead by then.
        into_line_14 = [step for step in control_steps if
                        details.executionPath[step['index']].startLine == 14]
        self.assertEqual(len(into_line_14), 1)
        self.assertEqual(
            {variable['name']: variable['value']
             for variable in into_line_14[0]['variables']}['p'],
            '0')
        self.assertIn(
            {'symbol': 'reg_$2<int b>',
             'range': '{ [-2147483648, -1], [1, 2147483647] }'},
            into_line_14[0]['path_condition'])

    def test_steps_keep_their_bug_path_order(self):
        """
        Storage splits events from control positions; `order` keeps where a
        step sits on the Bug Path, with event and control steps interleaved.
        """
        details = self._details('with_snapshots')

        trace = json.loads(details.constraintTrace)
        ordered = sorted(trace['steps'], key=lambda step: step['order'])

        # Hand-derived from demo/two-path.c: the path starts with the edges
        # into the `if` and its condition, then the "Assuming" event.
        self.assertEqual(
            [(step['kind'], step['order']) for step in ordered[:3]],
            [('control', 0), ('control', 1), ('event', 2)])
        self.assertEqual(ordered[2]['index'], 0)
        self.assertEqual(
            sorted(step['order'] for step in trace['steps']),
            [step['order'] for step in ordered])

    def test_trace_is_not_extended_report_data(self):
        """
        The new blob item type must not leak through extendedData, where an
        unhandled type would break the client's enum mapping.
        """
        details = self._details('with_snapshots')

        self.assertEqual(details.extendedData, [])

    def test_report_without_constraint_data(self):
        """
        A plist analyzed without the option has no trace in the API.
        """
        details = self._details('no_snapshots')

        self.assertIsNone(details.constraintTrace)
        self.assertTrue(details.pathEvents)

    def test_bug_path_is_feasible_without_what_if_constraints(self):
        """
        Z3 agrees with the analyzer that the reported Bug Path is possible.
        """
        result = self._check('with_snapshots')

        self.assertEqual(result.verdict, PathVerdict.FEASIBLE)
        self.assertEqual(result.baselineVerdict, PathVerdict.FEASIBLE)
        self.assertIsNone(result.reason)
        self.assertIsNone(result.baselineReason)

    def test_b_equal_to_zero_makes_this_path_infeasible(self):
        """
        The demo's Bug Path assumes `b` is not 0, so `b == 0` rules this path
        out, while the bug stays reachable through `a`.
        """
        step = self._event_step('with_snapshots',
                                "Assuming 'b' is not equal to 0")

        result = self._check('with_snapshots', (step, 'b == 0'))

        self.assertEqual(result.verdict, PathVerdict.INFEASIBLE)
        self.assertEqual(result.baselineVerdict, PathVerdict.FEASIBLE)

    def test_consistent_constraint_keeps_this_path_feasible(self):
        step = self._event_step('with_snapshots',
                                "Assuming 'b' is not equal to 0")

        for text in ['b == 5', 'b < 0', 'a <= 0']:
            result = self._check('with_snapshots', (step, text))
            self.assertEqual(result.verdict, PathVerdict.FEASIBLE, text)

    def test_variable_resolves_to_its_symbol_at_the_step(self):
        """
        `a` is constrained to 0 at the first step already, and dead by the
        last one; a term on it is still checked against that constraint.
        """
        first = self._event_step('with_snapshots',
                                 "Assuming 'a' is equal to 0")

        self.assertEqual(
            self._check('with_snapshots', (first, 'a > 0')).verdict,
            PathVerdict.INFEASIBLE)
        self.assertEqual(
            self._check('with_snapshots', (first, 'a == 0')).verdict,
            PathVerdict.FEASIBLE)

    def test_unknown_variable_gives_unknown(self):
        step = self._event_step('with_snapshots',
                                "Assuming 'b' is not equal to 0")

        result = self._check('with_snapshots', (step, 'q == 0'))

        self.assertEqual(result.verdict, PathVerdict.UNKNOWN)
        self.assertIn('`q`', result.reason)
        self.assertEqual(result.baselineVerdict, PathVerdict.FEASIBLE)

    def test_baseline_refuted_by_z3_is_reported_separately(self):
        """
        The range-based solver accepted `x * x == -1`, which no 32-bit square
        satisfies, so this path is infeasible before any What-If Constraint.
        """
        self.assertEqual(self._check('z3_refuted').baselineVerdict,
                         PathVerdict.INFEASIBLE)

        step = self._event_step('z3_refuted', "Assuming the condition is true")
        result = self._check('z3_refuted', (step, 'x == 3'))

        self.assertEqual(result.baselineVerdict, PathVerdict.INFEASIBLE)
        self.assertEqual(result.verdict, PathVerdict.INFEASIBLE)

    def test_without_smtlib_check_is_unknown(self):
        """
        A Clang without Z3 records readable ranges only, and the check says
        why it has no answer instead of failing.
        """
        details = self._details('no_smtlib')
        self.assertTrue(json.loads(details.constraintTrace)['steps'])

        step = self._event_step('no_smtlib', "Assuming 'b' is not equal to 0")
        result = self._check('no_smtlib', (step, 'b == 0'))

        self.assertEqual(result.verdict, PathVerdict.UNKNOWN)
        self.assertEqual(result.baselineVerdict, PathVerdict.UNKNOWN)
        self.assertIn('Clang built with Z3', result.reason)
        self.assertIn('this path', result.baselineReason)

    def test_without_snapshots_check_is_unknown(self):
        result = self._check('no_snapshots')

        self.assertEqual(result.verdict, PathVerdict.UNKNOWN)
        self.assertIn('this path', result.reason)

    def test_terms_joined_by_and_all_hold(self):
        step = self._event_step('with_snapshots',
                                "Assuming 'b' is not equal to 0")

        self.assertEqual(
            self._check('with_snapshots', (step, 'a == 0 && b > 3')).verdict,
            PathVerdict.FEASIBLE)
        self.assertEqual(
            self._check('with_snapshots', (step, 'b > 3 && b < 2')).verdict,
            PathVerdict.INFEASIBLE)

    def test_constraints_on_several_steps_apply_together(self):
        """
        `a == 0` at the first step and `b == 3` at the second are both
        consistent with this path; `b == 0` at the second step is not, and
        rules it out together with any other constraint.
        """
        first = self._event_step('with_snapshots',
                                 "Assuming 'a' is equal to 0")
        second = self._event_step('with_snapshots',
                                  "Assuming 'b' is not equal to 0")

        self.assertEqual(
            self._check('with_snapshots',
                        (first, 'a == 0'), (second, 'b == 3')).verdict,
            PathVerdict.FEASIBLE)
        self.assertEqual(
            self._check('with_snapshots',
                        (first, 'a == 0'), (second, 'b == 0')).verdict,
            PathVerdict.INFEASIBLE)

    def test_concrete_address_is_compared_directly(self):
        """
        Hand-derived from demo/concrete-value.c: `p` holds &x while `q` is
        assumed null, so `p == 0` there rules this path out.
        """
        step = self._event_step('concrete_value', "Assuming 'q' is null")

        for text, verdict in [('p == 0', PathVerdict.INFEASIBLE),
                              ('p == null', PathVerdict.INFEASIBLE),
                              ('p != null', PathVerdict.FEASIBLE),
                              ('q == null && p != 0', PathVerdict.FEASIBLE),
                              ('q != null', PathVerdict.INFEASIBLE)]:
            result = self._check('concrete_value', (step, text))
            self.assertEqual(result.verdict, verdict, text)
            self.assertEqual(result.baselineVerdict, PathVerdict.FEASIBLE)

    def test_concrete_integer_is_compared_directly(self):
        """ After the null store, `p` holds the integer 0. """
        step = self._event_step('concrete_value',
                                "Null pointer value stored to 'p'")

        self.assertEqual(
            self._check('concrete_value', (step, 'p == null')).verdict,
            PathVerdict.FEASIBLE)
        self.assertEqual(
            self._check('concrete_value', (step, 'p != 0')).verdict,
            PathVerdict.INFEASIBLE)

    def test_address_against_a_number_is_unknown(self):
        step = self._event_step('concrete_value', "Assuming 'q' is null")

        result = self._check('concrete_value', (step, 'p == 4096'))

        self.assertEqual(result.verdict, PathVerdict.UNKNOWN)
        self.assertIn('`p` holds &x', result.reason)
        self.assertEqual(result.reasonConstraintIndex, 0)

    def test_syntax_error_is_reported_apart_from_verdicts(self):
        step = self._event_step('with_snapshots',
                                "Assuming 'b' is not equal to 0")

        result = self._check('with_snapshots',
                             (step, 'b == 3'), (step, 'a = 0'))

        self.assertEqual(result.verdict, PathVerdict.UNKNOWN)
        self.assertEqual(result.baselineVerdict, PathVerdict.FEASIBLE)
        self.assertEqual(result.syntaxError.constraintIndex, 1)
        self.assertEqual(result.syntaxError.offset, 2)
        self.assertEqual(result.syntaxError.message,
                         'Expected an operator (`==`, `!=`, `<`, `<=`, `>`, '
                         '`>=`), found `=`.')

    def test_unknown_reason_names_its_constraint(self):
        first = self._event_step('with_snapshots',
                                 "Assuming 'a' is equal to 0")
        second = self._event_step('with_snapshots',
                                  "Assuming 'b' is not equal to 0")

        result = self._check('with_snapshots',
                             (first, 'a == 0'), (second, 'q == 0'))

        self.assertEqual(result.verdict, PathVerdict.UNKNOWN)
        self.assertEqual(result.reasonConstraintIndex, 1)
        self.assertIsNone(result.syntaxError)

    def test_holds_throughout_constrains_both_values_of_a_global(self):
        """
        Hand-derived from demo/opaque-call.c: `g` holds one symbol, assumed
        non-null, until `refresh()` replaces it with another, which the path
        assumes null. Anchored, `g != null` is about the first value only;
        holding throughout, it is about both.
        """
        step = self._event_step('opaque_call', "Assuming 'g' is non-null")

        for holds_throughout in (None, False):
            result = self._check('opaque_call',
                                 (step, 'g != null', holds_throughout))
            self.assertEqual(result.verdict, PathVerdict.FEASIBLE)
            self.assertIsNone(result.firstDeadStep)

        result = self._check('opaque_call', (step, 'g != null', True))
        self.assertEqual(result.verdict, PathVerdict.INFEASIBLE)
        self.assertEqual(result.baselineVerdict, PathVerdict.FEASIBLE)

        # The second value is assumed null from the edge into `if (g)` on,
        # which comes before the "Assuming 'g' is null" event.
        dies = self._first_step_constraining('opaque_call', 'derived_')
        self.assertEqual(result.firstDeadStep, dies)
        self.assertLess(
            dies, self._event_step('opaque_call', "Assuming 'g' is null"))

    def test_anchored_after_the_call_constrains_the_second_value(self):
        step = self._event_step('opaque_call', "Value assigned to 'g'")

        result = self._check('opaque_call', (step, 'g != null'))

        self.assertEqual(result.verdict, PathVerdict.INFEASIBLE)
        self.assertEqual(result.firstDeadStep,
                         self._first_step_constraining('opaque_call',
                                                       'derived_'))

    def test_first_dead_step_can_come_before_the_anchor(self):
        """
        `b == 0` anchored at the dereference contradicts `b != 0`, which the
        path assumed at its second branch.
        """
        anchor = self._event_step(
            'with_snapshots',
            "Dereference of null pointer (loaded from variable 'p')")

        result = self._check('with_snapshots', (anchor, 'b == 0'))

        self.assertEqual(result.verdict, PathVerdict.INFEASIBLE)
        dies = self._first_step_constraining('with_snapshots', 'reg_$2')
        self.assertEqual(result.firstDeadStep, dies)
        self.assertLess(dies, anchor)
        self.assertLessEqual(
            dies, self._event_step('with_snapshots',
                                   "Assuming 'b' is not equal to 0"))

    def test_holds_throughout_on_concrete_values(self):
        """
        `p` holds &x and later null, both concrete, and each is decided where
        `p` holds it.
        """
        step = self._event_step('concrete_value', "Assuming 'q' is null")
        stored = self._event_step('concrete_value',
                                  "Null pointer value stored to 'p'")

        result = self._check('concrete_value', (step, 'p != null', True))
        self.assertEqual(result.verdict, PathVerdict.INFEASIBLE)
        self.assertLessEqual(result.firstDeadStep, stored)
        self.assertGreater(result.firstDeadStep, step)

    def test_holds_throughout_without_a_value_anywhere_is_unknown(self):
        step = self._event_step('opaque_call', "Assuming 'g' is non-null")

        result = self._check('opaque_call', (step, 'q == 0', True))

        self.assertEqual(result.verdict, PathVerdict.UNKNOWN)
        self.assertIn('any Path Step', result.reason)
        self.assertEqual(result.reasonConstraintIndex, 0)

    def test_check_writes_nothing_to_the_database(self):
        """
        What-If Constraints stay temporary: the product database is the same,
        row for row, before and after checks of every outcome.
        """
        if env.get_postgresql_cfg():
            self.skipTest("Compares the SQLite product database file.")

        # Where add_test_package_product puts it.
        database = os.path.join(
            env.get_workspace(None), 'global_simple_server',
            os.path.basename(self._test_workspace) + '.sqlite')
        self.assertTrue(os.path.isfile(database), database)

        def dump():
            connection = sqlite3.connect(f'file:{database}?mode=ro',
                                         uri=True)
            try:
                return list(connection.iterdump())
            finally:
                connection.close()

        before = dump()
        step = self._event_step('with_snapshots',
                                "Assuming 'b' is not equal to 0")
        self._check('with_snapshots', (step, 'b == 0'))
        self._check('with_snapshots', (step, 'b == 5'))
        self._check('with_snapshots', (step, 'b = 5'))
        self._check('z3_refuted')
        self._check('no_smtlib')

        self.assertEqual(dump(), before)
